use crate::json::{obj, JsonValue};

fn opt_s(v: &Option<String>) -> JsonValue {
    match v {
        Some(s) => JsonValue::String(s.clone()),
        None => JsonValue::Null,
    }
}

#[derive(Debug, Clone)]
pub enum GameEvent {
    TurnStarted { player_id: String, turn: u32 },
    RoundStarted { round: u32 },
    CardDrawn { player_id: String, card_ids: Vec<String> },
    DeckShuffled { deck_count: usize, player_id: Option<String> },
    CardPlayed { player_id: String, card_id: String, card_type: String },
    CardsFused { player_id: String, card_ids: [String; 2], card_id: String, from: String, to: String },
    DiscardRequired { player_id: String, count: usize },
    CardDiscarded { player_id: String, card_ids: Vec<String> },
    SoldierDeployed {
        player_id: String,
        soldier_id: String,
        soldier_type: String,
        road_id: String,
        target_id: String,
        position: usize,
        hp: i32,
        attack: i32,
    },
    SoldierMoved { player_id: String, soldier_id: String, road_id: String, from: usize, to: usize, cause: Option<String> },
    SoldiersClashed { road_id: String, square: usize },
    SoldierDamaged { player_id: String, soldier_id: String, amount: i32, hp: i32, cause: String, blocked: i32 },
    SoldierDestroyed { player_id: String, soldier_id: String, reason: String },
    SoldierShot { player_id: String, soldier_id: String, amount: i32 },
    SpellCast { player_id: String, spell_type: String, target: String, target_kind: String, road_id: Option<String> },
    CastleDamaged { player_id: String, amount: i32, blocked: i32, hp: i32, source_kind: String },
    CastleHealed { player_id: String, amount: i32, hp: i32 },
    WeaponEquipped { player_id: String, soldier_id: String, weapon_type: String, attack: i32, element: Option<String> },
    ShieldAdded { player_id: String, soldier_id: String, amount: i32, shield: i32 },
    CastleArmored { player_id: String, armor: i32 },
    ArmorExpired { player_id: String },
    StatusApplied { player_id: String, soldier_id: String, status: String, turns: i32 },
    StatusCleared { player_id: String, soldier_id: String, status: String },
    MonsterAppeared { monster_id: String, monster_type: String, road_id: String, square: usize, hp: i32, attack: i32 },
    MonsterAttackedCastle { monster_id: String, player_id: String, amount: i32, hp: i32 },
    MonsterDamaged { monster_id: String, amount: i32, hp: i32 },
    MonsterDefeated { monster_id: String, player_id: String, reward: i32 },
    CoinsChanged { player_id: String, delta: i32, coins: i32, reason: String },
    MpChanged { player_id: String, delta: i32, mp: i32, reason: String },
    UpgradeBought { player_id: String, upgrade_id: String, cost: i32 },
    SoldierBuffed { player_id: String, soldier_id: String, attack: i32 },
    DiceRolled { player_id: String, dice_type: String, value: u32, amount: i32 },
    DefenseRequested { defender_id: String, attacker_id: String, kind: String, amount: i32 },
    DefenseEnded { defender_id: String },
    SpellReflected { defender_id: String, attacker_id: String, amount: i32 },
    SoldierDecoyed { defender_id: String, attacker_id: String, soldier_id: String },
    CardStolen { player_id: String, victim_id: String, card_id: String },
    SpiritSummoned { player_id: String, spirit_type: String, spirit: String, amount: i32, turns: i32 },
    SpiritTriggered { player_id: String, spirit_type: String, spirit: String, amount: i32 },
    OverdriveChanged { player_id: String, active: bool },
    GameOver { winner: Option<String>, reason: String },
}

impl GameEvent {
    pub fn to_json(&self) -> JsonValue {
        match self {
            GameEvent::TurnStarted { player_id, turn } => obj(vec![
                ("type", JsonValue::String("turnStarted".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("turn", JsonValue::Number(*turn as f64)),
            ]),
            GameEvent::RoundStarted { round } => obj(vec![
                ("type", JsonValue::String("roundStarted".into())),
                ("round", JsonValue::Number(*round as f64)),
            ]),
            GameEvent::CardDrawn { player_id, card_ids } => obj(vec![
                ("type", JsonValue::String("cardDrawn".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("cardIds", JsonValue::Array(card_ids.iter().cloned().map(JsonValue::String).collect())),
            ]),
            GameEvent::DeckShuffled { deck_count, player_id } => obj(vec![
                ("type", JsonValue::String("deckShuffled".into())),
                ("deckCount", JsonValue::Number(*deck_count as f64)),
                ("playerId", opt_s(player_id)),
            ]),
            GameEvent::CardPlayed { player_id, card_id, card_type } => obj(vec![
                ("type", JsonValue::String("cardPlayed".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("cardId", JsonValue::String(card_id.clone())),
                ("cardType", JsonValue::String(card_type.clone())),
            ]),
            GameEvent::CardsFused { player_id, card_ids, card_id, from, to } => obj(vec![
                ("type", JsonValue::String("cardsFused".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("cardIds", JsonValue::Array(vec![JsonValue::String(card_ids[0].clone()), JsonValue::String(card_ids[1].clone())])),
                ("cardId", JsonValue::String(card_id.clone())),
                ("from", JsonValue::String(from.clone())),
                ("to", JsonValue::String(to.clone())),
            ]),
            GameEvent::DiscardRequired { player_id, count } => obj(vec![
                ("type", JsonValue::String("discardRequired".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("count", JsonValue::Number(*count as f64)),
            ]),
            GameEvent::CardDiscarded { player_id, card_ids } => obj(vec![
                ("type", JsonValue::String("cardDiscarded".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("cardIds", JsonValue::Array(card_ids.iter().cloned().map(JsonValue::String).collect())),
            ]),
            GameEvent::SoldierDeployed { player_id, soldier_id, soldier_type, road_id, target_id, position, hp, attack } => obj(vec![
                ("type", JsonValue::String("soldierDeployed".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("soldierId", JsonValue::String(soldier_id.clone())),
                ("soldierType", JsonValue::String(soldier_type.clone())),
                ("roadId", JsonValue::String(road_id.clone())),
                ("targetId", JsonValue::String(target_id.clone())),
                ("position", JsonValue::Number(*position as f64)),
                ("hp", JsonValue::Number(*hp as f64)),
                ("attack", JsonValue::Number(*attack as f64)),
            ]),
            GameEvent::SoldierMoved { player_id, soldier_id, road_id, from, to, cause } => obj(vec![
                ("type", JsonValue::String("soldierMoved".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("soldierId", JsonValue::String(soldier_id.clone())),
                ("roadId", JsonValue::String(road_id.clone())),
                ("from", JsonValue::Number(*from as f64)),
                ("to", JsonValue::Number(*to as f64)),
                ("cause", opt_s(cause)),
            ]),
            GameEvent::SoldiersClashed { road_id, square } => obj(vec![
                ("type", JsonValue::String("soldiersClashed".into())),
                ("roadId", JsonValue::String(road_id.clone())),
                ("square", JsonValue::Number(*square as f64)),
            ]),
            GameEvent::SoldierDamaged { player_id, soldier_id, amount, hp, cause, blocked } => obj(vec![
                ("type", JsonValue::String("soldierDamaged".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("soldierId", JsonValue::String(soldier_id.clone())),
                ("amount", JsonValue::Number(*amount as f64)),
                ("hp", JsonValue::Number(*hp as f64)),
                ("cause", JsonValue::String(cause.clone())),
                ("blocked", JsonValue::Number(*blocked as f64)),
            ]),
            GameEvent::SoldierDestroyed { player_id, soldier_id, reason } => obj(vec![
                ("type", JsonValue::String("soldierDestroyed".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("soldierId", JsonValue::String(soldier_id.clone())),
                ("reason", JsonValue::String(reason.clone())),
            ]),
            GameEvent::SoldierShot { player_id, soldier_id, amount } => obj(vec![
                ("type", JsonValue::String("soldierShot".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("soldierId", JsonValue::String(soldier_id.clone())),
                ("amount", JsonValue::Number(*amount as f64)),
            ]),
            GameEvent::SpellCast { player_id, spell_type, target, target_kind, road_id } => obj(vec![
                ("type", JsonValue::String("spellCast".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("spellType", JsonValue::String(spell_type.clone())),
                ("target", JsonValue::String(target.clone())),
                ("targetKind", JsonValue::String(target_kind.clone())),
                ("roadId", opt_s(road_id)),
            ]),
            GameEvent::CastleDamaged { player_id, amount, blocked, hp, source_kind } => obj(vec![
                ("type", JsonValue::String("castleDamaged".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("amount", JsonValue::Number(*amount as f64)),
                ("blocked", JsonValue::Number(*blocked as f64)),
                ("hp", JsonValue::Number(*hp as f64)),
                ("sourceKind", JsonValue::String(source_kind.clone())),
            ]),
            GameEvent::CastleHealed { player_id, amount, hp } => obj(vec![
                ("type", JsonValue::String("castleHealed".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("amount", JsonValue::Number(*amount as f64)),
                ("hp", JsonValue::Number(*hp as f64)),
            ]),
            GameEvent::WeaponEquipped { player_id, soldier_id, weapon_type, attack, element } => obj(vec![
                ("type", JsonValue::String("weaponEquipped".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("soldierId", JsonValue::String(soldier_id.clone())),
                ("weaponType", JsonValue::String(weapon_type.clone())),
                ("attack", JsonValue::Number(*attack as f64)),
                ("element", opt_s(element)),
            ]),
            GameEvent::ShieldAdded { player_id, soldier_id, amount, shield } => obj(vec![
                ("type", JsonValue::String("shieldAdded".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("soldierId", JsonValue::String(soldier_id.clone())),
                ("amount", JsonValue::Number(*amount as f64)),
                ("shield", JsonValue::Number(*shield as f64)),
            ]),
            GameEvent::CastleArmored { player_id, armor } => obj(vec![
                ("type", JsonValue::String("castleArmored".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("armor", JsonValue::Number(*armor as f64)),
            ]),
            GameEvent::ArmorExpired { player_id } => obj(vec![
                ("type", JsonValue::String("armorExpired".into())),
                ("playerId", JsonValue::String(player_id.clone())),
            ]),
            GameEvent::StatusApplied { player_id, soldier_id, status, turns } => obj(vec![
                ("type", JsonValue::String("statusApplied".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("soldierId", JsonValue::String(soldier_id.clone())),
                ("status", JsonValue::String(status.clone())),
                ("turns", JsonValue::Number(*turns as f64)),
            ]),
            GameEvent::StatusCleared { player_id, soldier_id, status } => obj(vec![
                ("type", JsonValue::String("statusCleared".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("soldierId", JsonValue::String(soldier_id.clone())),
                ("status", JsonValue::String(status.clone())),
            ]),
            GameEvent::MonsterAppeared { monster_id, monster_type, road_id, square, hp, attack } => obj(vec![
                ("type", JsonValue::String("monsterAppeared".into())),
                ("monsterId", JsonValue::String(monster_id.clone())),
                ("monsterType", JsonValue::String(monster_type.clone())),
                ("roadId", JsonValue::String(road_id.clone())),
                ("square", JsonValue::Number(*square as f64)),
                ("hp", JsonValue::Number(*hp as f64)),
                ("attack", JsonValue::Number(*attack as f64)),
            ]),
            GameEvent::MonsterAttackedCastle { monster_id, player_id, amount, hp } => obj(vec![
                ("type", JsonValue::String("monsterAttackedCastle".into())),
                ("monsterId", JsonValue::String(monster_id.clone())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("amount", JsonValue::Number(*amount as f64)),
                ("hp", JsonValue::Number(*hp as f64)),
            ]),
            GameEvent::MonsterDamaged { monster_id, amount, hp } => obj(vec![
                ("type", JsonValue::String("monsterDamaged".into())),
                ("monsterId", JsonValue::String(monster_id.clone())),
                ("amount", JsonValue::Number(*amount as f64)),
                ("hp", JsonValue::Number(*hp as f64)),
            ]),
            GameEvent::MonsterDefeated { monster_id, player_id, reward } => obj(vec![
                ("type", JsonValue::String("monsterDefeated".into())),
                ("monsterId", JsonValue::String(monster_id.clone())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("reward", JsonValue::Number(*reward as f64)),
            ]),
            GameEvent::CoinsChanged { player_id, delta, coins, reason } => obj(vec![
                ("type", JsonValue::String("coinsChanged".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("delta", JsonValue::Number(*delta as f64)),
                ("coins", JsonValue::Number(*coins as f64)),
                ("reason", JsonValue::String(reason.clone())),
            ]),
            GameEvent::MpChanged { player_id, delta, mp, reason } => obj(vec![
                ("type", JsonValue::String("mpChanged".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("delta", JsonValue::Number(*delta as f64)),
                ("mp", JsonValue::Number(*mp as f64)),
                ("reason", JsonValue::String(reason.clone())),
            ]),
            GameEvent::UpgradeBought { player_id, upgrade_id, cost } => obj(vec![
                ("type", JsonValue::String("upgradeBought".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("upgradeId", JsonValue::String(upgrade_id.clone())),
                ("cost", JsonValue::Number(*cost as f64)),
            ]),
            GameEvent::SoldierBuffed { player_id, soldier_id, attack } => obj(vec![
                ("type", JsonValue::String("soldierBuffed".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("soldierId", JsonValue::String(soldier_id.clone())),
                ("attack", JsonValue::Number(*attack as f64)),
            ]),
            GameEvent::DiceRolled { player_id, dice_type, value, amount } => obj(vec![
                ("type", JsonValue::String("diceRolled".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("diceType", JsonValue::String(dice_type.clone())),
                ("value", JsonValue::Number(*value as f64)),
                ("amount", JsonValue::Number(*amount as f64)),
            ]),
            GameEvent::DefenseRequested { defender_id, attacker_id, kind, amount } => obj(vec![
                ("type", JsonValue::String("defenseRequested".into())),
                ("defenderId", JsonValue::String(defender_id.clone())),
                ("attackerId", JsonValue::String(attacker_id.clone())),
                ("kind", JsonValue::String(kind.clone())),
                ("amount", JsonValue::Number(*amount as f64)),
            ]),
            GameEvent::DefenseEnded { defender_id } => obj(vec![
                ("type", JsonValue::String("defenseEnded".into())),
                ("defenderId", JsonValue::String(defender_id.clone())),
            ]),
            GameEvent::SpellReflected { defender_id, attacker_id, amount } => obj(vec![
                ("type", JsonValue::String("spellReflected".into())),
                ("defenderId", JsonValue::String(defender_id.clone())),
                ("attackerId", JsonValue::String(attacker_id.clone())),
                ("amount", JsonValue::Number(*amount as f64)),
            ]),
            GameEvent::SoldierDecoyed { defender_id, attacker_id, soldier_id } => obj(vec![
                ("type", JsonValue::String("soldierDecoyed".into())),
                ("defenderId", JsonValue::String(defender_id.clone())),
                ("attackerId", JsonValue::String(attacker_id.clone())),
                ("soldierId", JsonValue::String(soldier_id.clone())),
            ]),
            GameEvent::CardStolen { player_id, victim_id, card_id } => obj(vec![
                ("type", JsonValue::String("cardStolen".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("victimId", JsonValue::String(victim_id.clone())),
                ("cardId", JsonValue::String(card_id.clone())),
            ]),
            GameEvent::SpiritSummoned { player_id, spirit_type, spirit, amount, turns } => obj(vec![
                ("type", JsonValue::String("spiritSummoned".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("spiritType", JsonValue::String(spirit_type.clone())),
                ("spirit", JsonValue::String(spirit.clone())),
                ("amount", JsonValue::Number(*amount as f64)),
                ("turns", JsonValue::Number(*turns as f64)),
            ]),
            GameEvent::SpiritTriggered { player_id, spirit_type, spirit, amount } => obj(vec![
                ("type", JsonValue::String("spiritTriggered".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("spiritType", JsonValue::String(spirit_type.clone())),
                ("spirit", JsonValue::String(spirit.clone())),
                ("amount", JsonValue::Number(*amount as f64)),
            ]),
            GameEvent::OverdriveChanged { player_id, active } => obj(vec![
                ("type", JsonValue::String("overdriveChanged".into())),
                ("playerId", JsonValue::String(player_id.clone())),
                ("active", JsonValue::Bool(*active)),
            ]),
            GameEvent::GameOver { winner, reason } => obj(vec![
                ("type", JsonValue::String("gameOver".into())),
                ("winner", opt_s(winner)),
                ("reason", JsonValue::String(reason.clone())),
            ]),
        }
    }
}

pub fn events_to_json_string(events: &[GameEvent]) -> String {
    JsonValue::Array(events.iter().map(|e| e.to_json()).collect()).to_json_string()
}
